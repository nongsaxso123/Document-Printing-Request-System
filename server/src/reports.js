const FILE_BASE = {
  history: { th: "รายงานประวัติคำขอ", en: "request-history-report" },
  dashboard: { th: "รายงานสรุปการใช้กระดาษ", en: "paper-usage-report" },
  evaluations: { th: "รายงานผลประเมินความพึงพอใจ", en: "satisfaction-report" }
};

async function sendWorkbook(res, wb, kind, lang) {
  lang = langOf(lang);
  const d = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  const stamp = `${lang === "en" ? d.getFullYear() : d.getFullYear() + 543}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  const name = `${FILE_BASE[kind][lang]}_${stamp}.xlsx`;
  const ascii = `${FILE_BASE[kind].en}_${stamp}.xlsx`;
  res.setHeader("Content-Type", "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
  // ASCII fallback + RFC 5987 UTF-8 name, so browsers keep the Thai filename.
  res.setHeader("Content-Disposition", `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(name)}`);
  const buffer = await wb.xlsx.writeBuffer();
  res.send(Buffer.from(buffer));
}

